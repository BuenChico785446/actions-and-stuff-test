    public static String block(String bedrockName) {
        return BLOCKS.getOrDefault(bedrockName, bedrockName);
    }

    public static String item(String bedrockName) {
        return ITEMS.getOrDefault(bedrockName, bedrockName);
    }

    public static boolean renamedBlock(String bedrockName) {
        return BLOCKS.containsKey(bedrockName);
    }

    public static boolean renamedItem(String bedrockName) {
        return ITEMS.containsKey(bedrockName);
    }
